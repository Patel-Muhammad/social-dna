import pandas as pd
import streamlit as st

from components import charts
from components.context import get_context
from components.metric_cards import feature_chips, metric_cards
from components.sidebar import render_sidebar
from components.theme import callout, page_header
from llm.gemini_client import GeminiUnavailableError

ctx = get_context()
render_sidebar(ctx)
svc = ctx.service
page_header("Community Profiles", "Who is in a community, what they commonly like, and how connected they are.")

cid = st.selectbox("Choose a community", svc.community_ids(), format_func=lambda c: f"Community {c}  ·  "
                   f"{int(svc.communities.loc[c].member_count):,} members")
d = svc.get_community_details(cid)
metric_cards([
    ("Members", f"{d['member_count']:,}", f"{d['percentage_of_network']:.1f}% of the network"),
    ("Internal friendships", f"{d['internal_edges']:,}", f"avg {d['avg_internal_degree']:.1f} per member"),
    ("External friendships", f"{d['external_edges']:,}", f"conductance {d['conductance']:.2f}"),
    ("Within-community cosine", f"{d['within_community_cosine']:.3f}", f"network profile match {d['cosine_to_network']:.2f}"),
])

st.subheader("AI-generated description")
stored = svc.communities.loc[cid].description
if isinstance(stored, str) and stored:
    st.markdown(stored)
    st.caption(f"Generated by {svc.communities.loc[cid].description_model} from the measured values on this page.")
else:
    st.caption("No description generated yet for this community.")
if st.button("Generate with Gemini", disabled=not ctx.analyst.gemini.is_configured):
    with st.spinner("Asking Gemini to describe verified results..."):
        try:
            text = ctx.analyst.describe_community(cid)
            ctx.repo.set_description(int(svc.communities.loc[cid].community_row_id), text,
                                     ctx.analyst.gemini.last_model_used or "gemini")
            svc.communities.loc[cid, "description"] = text
            st.markdown(text)
        except GeminiUnavailableError as exc:
            st.error(str(exc))
if not ctx.analyst.gemini.is_configured:
    callout("Gemini is not configured. Add <code>GEMINI_API_KEY</code> to <code>.env</code> and restart. "
            "All measured values below remain available.", "warn")

st.subheader("Interests")
callout("<b>Measured:</b> shares of members who like each artist feature. <b>Not measured:</b> artist names or genres. "
        "This dataset only provides anonymous feature IDs, so we never guess what they are.")
a, b = st.columns(2)
with a:
    st.markdown("**Most common features** (liked by the most members)")
    st.plotly_chart(charts.feature_bar(d["common_features"], ""), use_container_width=True)
with b:
    st.markdown("**Most distinctive features** (over-represented vs. the whole network)")
    st.plotly_chart(charts.feature_bar(d["distinctive_features"], "", color="#0D9488"), use_container_width=True)
with st.expander("Full tables with lift and network prevalence"):
    full = svc.get_common_interests(cid)
    st.dataframe(pd.DataFrame(full["common_features"]).drop(columns=["label"]), hide_index=True, use_container_width=True)
    st.dataframe(pd.DataFrame(full["distinctive_features"]).drop(columns=["label"]), hide_index=True, use_container_width=True)
    st.caption("lift = prevalence in community / prevalence in network. distinctiveness = prevalence × log2(lift).")

st.subheader("Most similar communities")
sim = pd.DataFrame(d["most_similar_communities"]).rename(columns={
    "other": "Community", "cosine_similarity": "Cosine", "jaccard_similarity": "Jaccard", "cross_edges": "Friendships between"})
st.dataframe(sim, hide_index=True, use_container_width=True)
